/** Assemble shared bitmap glyphs with a one-pixel outline for any desktop background. */
export function pixelLabel(text: string, ink: number, outline: number): Sprite {
  const letters = [...text].map(letter => PIXEL_FONT[letter] ?? PIXEL_FONT[" "]!);
  const width = Math.max(1, letters.length * 6 - 1) + 2;
  const pixels = Array.from({ length: 9 }, () => Array<string>(width).fill("."));
  const points: Array<[number, number]> = [];
  letters.forEach((letter, i) => letter.split("/").forEach((row, y) => [...row].forEach((bit, x) => {
    if (bit === "1") points.push([i * 6 + x + 1, y + 1]);
  })));
  for (const [x, y] of points) {
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) pixels[y + dy]![x + dx] = "o";
  }
  for (const [x, y] of points) pixels[y]![x] = "#";
  return { rows: pixels.map(row => row.join("")), palette: { "#": ink, "o": outline } };
}
